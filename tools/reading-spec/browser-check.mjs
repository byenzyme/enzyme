// Optional browser smoke test. Point PLAYWRIGHT_MODULE at an installed playwright module.
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const artifacts = await mkdtemp(join(tmpdir(), 'enzyme-reading-browser-'));
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1200}});
const errors=[]; page.on('pageerror', e => errors.push(e.message));
await page.goto(process.env.READING_SPEC_URL || 'http://127.0.0.1:4178');
await page.getByText('Compiled · preview',{exact:true}).waitFor();
assert.ok((await page.locator('.reading-card').count()) >= 6);
await page.screenshot({path:join(artifacts, 'desktop.png'),fullPage:true});
await page.getByRole('tab',{name:'Config',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Download TOML'}).isDisabled(),true);
await page.getByLabel('Example program').selectOption('current-engine');
await page.getByText('Compiled · export ready',{exact:true}).waitFor();
assert.equal(await page.getByRole('button',{name:'Download TOML'}).isDisabled(),false);
await page.getByRole('tab',{name:'Agent instructions',exact:true}).click();
assert.match(await page.locator('#result').innerText(),/enzyme petri --query/);
const editor=page.getByLabel('Reading program');
await editor.fill('vault "/notes" {\n learn questions from folder "people" about typo\n}');
await page.getByText('Check syntax',{exact:true}).waitFor();
assert.match(await page.locator('#diagnostics').innerText(),/Unknown profile/);
await page.locator('#diagnostics button').first().click();
assert.equal(await editor.evaluate(e=>document.activeElement===e),true);
await page.getByLabel('Example program').selectOption('memory');
await page.getByText('Compiled · export ready',{exact:true}).waitFor();
assert.match(await page.locator('#result').innerText(),/Remember in/);
await page.getByRole('tab',{name:'Reading',exact:true}).click();
await page.getByLabel('Example program').selectOption('overrides');
await page.getByText('Compiled · preview',{exact:true}).waitFor();
assert.match(await page.locator('#result').innerText(),/all periods equally/);
// Treat pasted source strictly as data, including in syntax highlighting.
await editor.fill('vault "/notes" { when asked { "<img src=x onerror=alert(1)>" } }');
await page.getByText('Compiled · export ready',{exact:true}).waitFor();
assert.equal(await page.locator('img').count(),0);
await page.getByLabel('Example program').selectOption('vault');
await page.getByText('Compiled · preview',{exact:true}).waitFor();
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false);
await page.screenshot({path:join(artifacts, 'mobile.png'),fullPage:true});
assert.deepEqual(errors,[]);
console.log('Browser checks passed: examples, config gate, instructions, diagnostics, overrides, escaping, mobile layout.');
console.log(`Screenshots: ${artifacts}`);
await browser.close();
